/**
 * @file    control.h
 * @brief   倒立摆的双环 PID 控制器：串级结构 + 状态机 + 倒下保护。
 *
 * ── 被控对象 ────────────────────────────────────────────────────────
 *   旋转倒立摆（Furuta 摆）：电机驱动**横杆**在水平面内 360° 旋转，
 *   摆杆铰接在横杆自由端、在竖直平面内自由摆动。
 *   两个自由度、一个执行器 —— 典型的欠驱动系统。
 *
 *   ⚠️ 容易搞混的一点：角度传感器（电位器）测的是**摆杆**的角度，
 *      编码器测的是**横杆**的角度。两者是不同的轴，别看成同一个。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 为什么要两个环 ──────────────────────────────────────────────────
 *   只有一个执行器，却要同时管两件事：把摆杆立住、把横杆钉住。
 *   串级 PID 的思路是分优先级：
 *
 *     外环（位置环，50 ms）—— "横杆该在哪" → 输出**角度修正量**
 *     内环（角度环，  5 ms）—— "摆杆该在什么角度" → 输出 **PWM**
 *
 *   外环的输出（±100 个 ADC 码）**不是直接给电机的**，而是去
 *   微调内环的目标角度：
 *
 *       AnglePID.Target = CENTER_ANGLE − LocationPID.Out
 *                                        ^^^^^^^^^^^^^^^^^^^^^^^
 *                                        负号：实测确定，见下
 *
 *   物理含义：横杆偏离目标位置越远，外环就把「摆杆该立的角度」
 *   偏得越多；内环为了够到那个偏掉的角度，就得让横杆转过去 ——
 *   于是摆杆始终立着，而横杆慢慢挪回目标位置。
 *
 *   **内环必须比外环快 10 倍以上**（这里是 5 ms vs 50 ms）：
 *   外环把内环当成一个「说去哪就去哪」的理想执行器，
 *   内环跟不上外环的指令，整个串级结构就不成立。
 *
 *   ⚠️ 那个负号为什么是负的：外环输出为正表示「横杆位置偏大，
 *      要往负方向转」。而在本套机构上，把摆杆目标角度**调小**
 *      （Target = CENTER − Out，Out>0 时为负偏移）才会让电机朝
 *      那个方向转。符号是由「电机转向 ↔ 编码器计数方向」和
 *      「摆杆倾斜方向 ↔ 电位器读数方向」两组约定共同决定的，
 *      换电机/换接线就可能反。**调试时如果发现横杆越跑越远，
 *      第一个该怀疑的就是这个符号**，改这一处即可，不要去乱调增益。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 控制周期为什么锁在 1 ms 中断里 ──────────────────────────────────
 *   主循环里刷一次 OLED 要 ~30 ms（软件 I2C 写 1 KB 显存）。
 *   角度环周期 5 ms，如果跑在主循环里，实际周期会在 5~35 ms 之间乱跳，
 *   相当于给控制器灌了一路巨大的噪声，根本立不住。
 *
 *   所以控制环挂在 bsp_tick 的 1 ms 中断上，由它分频出 5 ms / 50 ms。
 *   主循环只剩「按键、串口、显示」这些对时间不敏感的事。
 *
 *   代价是**控制环跑在中断上下文里**，必须遵守快进快出的规矩：
 *   不许阻塞、不许 HAL_Delay、不许 printf、不许刷屏。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── ⚠️⚠️ 盲区陷阱，以及为什么本模块用**两个**窗口 ──────────────────
 *   电位器有约 25° 的机械盲区，**对准摆杆自然下垂的方向**。
 *   摆杆垂在下面时读数**没有意义** —— 但「没有意义」不等于「数值离谱」，
 *   这才是坑所在。2026-10-09 在本台设备上实测（摆杆自由下垂、静止）：
 *
 *       竖直向上（手扶）   2086
 *       自由下垂（松手）   1883 ± 7      ← 盲区里的无效读数
 *                                         却在 90 秒内**稳定不漂**
 *
 *   两者只差 **203 码 ≈ 16.6°**。而官方的倒下判定窗口是 `CENTER ± 500`
 *   = [1586, 2586] —— **1883 落在里面**。也就是说：
 *
 *       **「角度在 ±500 窗口内」根本不能证明摆杆是立着的。**
 *
 *   （注意：这跟「电气上 180° 应该对应 2200 个码」不矛盾。下垂位置在
 *     盲区里，读数由抽头分压的残值决定，跟杆的真实角度没有对应关系。
 *     拿它去和标定表对齐是问错了问题。）
 *
 *   于是把「判定摆杆立着」这一件事拆成两个**目的不同**的窗口：
 *
 *     ┌────────────┬──────────────┬─────────┬────────────────────────┐
 *     │ 窗口        │ 何时检查      │ 半宽度   │ 要防的事                │
 *     ├────────────┼──────────────┼─────────┼────────────────────────┤
 *     │ start_range│ 只在 RUN 瞬间 │ ±150    │ 躺着/垂着被误启动        │
 *     │            │              │ (≈12°)  │ 1883 被排除在外 ✓       │
 *     ├────────────┼──────────────┼─────────┼────────────────────────┤
 *     │ center_range│ 运行中每 1 ms│ ±500    │ 立着立着倒了            │
 *     │            │              │ (≈41°)  │ 从竖直到倒下**必然先    │
 *     │            │              │         │ 经过 41°**，那时读数还在│
 *     │            │              │         │ 有效区，必定触发 ✓      │
 *     └────────────┴──────────────┴─────────┴────────────────────────┘
 *
 *   **为什么不能只用一个 ±150**：运行中摆杆正常摆动就可能超过 12°，
 *   那样控制器会不停自我停机，调参根本进行不下去。
 *   **为什么不能只用一个 ±500**：躺着启动不了这一条就没了。
 *
 *   残留风险（**必须知道**）：如果整台支架是歪的（电机轴不竖直），
 *   「自由下垂」对应的读数会随**横杆方位**变化，±150 就未必总能把
 *   垂着的读数排除掉。当前这台实测下垂固定读 1883（横杆方位未变过），
 *   这一点没有验证过。所以规矩仍然是：
 *
 *       **启动前必须用手把摆杆扶到竖直附近再按 RUN。**
 *
 *   这一条对自动化调试脚本同样成立 —— agent 应当在 RUN 之前先
 *   `STAT` 一下，确认 ANGLE 落在 CENTER 附近，而不是假设它一定在。
 *
 *   （将来加了自动启摆（荡秋千）之后就不需要手扶了 —— 那是
 *      `control_state_t` 留了扩展位的原因，见下。）
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 本轮**不做**自动启摆 ────────────────────────────────────────────
 *   官方的 V1.1 综合程序有一套启摆状态机（状态 21~24 / 31~34），
 *   靠「摆到最高点顺势抖一下」逐次给摆杆注能量，把它荡到竖直附近，
 *   再交给双环 PID。用户参考的 15-倒立摆 工程**没有**这个，
 *   本轮范围也只是双环 PID，所以：
 *
 *     启动方式 = 手扶摆杆到竖直附近 → RUN → 松手
 *
 *   因此如果发现「按了 RUN 摆杆还是躺着不动」，那**不是控制器坏了**，
 *   是还没有启摆功能。`control_state_t` 用枚举而不是 bool，
 *   就是为了以后插一个 SWING_UP 状态不用推倒重来。
 * ────────────────────────────────────────────────────────────────────
 */

#ifndef APP_CONTROL_CONTROL_H
#define APP_CONTROL_CONTROL_H

#include <stdbool.h>
#include <stdint.h>

#include "error.h"

/**
 * 位置目标的绝对值上限（边沿）。408 边沿 = 横杆一圈，这里允许正反各 10 圈。
 *
 * 为什么要限：目标是**累积**的，按几次 K2 就能把它推到天文数字，
 * 而控制器会当真 —— 横杆就一直转下去，把电源线绞断。硬件上真的会。
 * 官方工程也是 ±4080。超过就**拒绝**（返回 ERR_INVALID_PARAM），
 * 而不是悄悄夹到边界 —— 夹紧会让「按了没反应」，比报错更难查。
 */
#define CONTROL_POS_TARGET_LIMIT    (4080)

/**
 * 控制器的运行状态。
 *
 * 用枚举而不是 bool，是为了**留出扩展位**：以后要加自动启摆，
 * 在这里插一个 CONTROL_STATE_SWING_UP 即可，不需要改动各处
 * 「if (running)」的判断逻辑（那些地方改判 `== RUN`）。
 */
typedef enum {
    CONTROL_STATE_STOP = 0,     /**< 停止：电机滑行，两个环都不算 */
    CONTROL_STATE_RUN,          /**< 运行：双环串级控制中 */
    /* CONTROL_STATE_SWING_UP,  预留：自动启摆（本工程未实现）*/
} control_state_t;

/**
 * 可以**在线改**的参数清单。
 *
 * 做成枚举而不是一堆 setter，是为了让串口调参层能用一个
 * 「名字 → 枚举」的表统一处理 SET/GET，加参数只需要改两处
 * （这里 + console.c 的名字表），不会漏掉某个命令。
 */
typedef enum {
    CONTROL_PARAM_AKP = 0,      /**< 角度环 Kp */
    CONTROL_PARAM_AKI,          /**< 角度环 Ki */
    CONTROL_PARAM_AKD,          /**< 角度环 Kd */
    CONTROL_PARAM_PKP,          /**< 位置环 Kp */
    CONTROL_PARAM_PKI,          /**< 位置环 Ki */
    CONTROL_PARAM_PKD,          /**< 位置环 Kd */
    CONTROL_PARAM_CENTER,       /**< 中心角度（ADC 码，摆杆竖直向上的读数）*/
    CONTROL_PARAM_RANGE,        /**< 运行中的倒下判定半窗口（ADC 码）*/
    CONTROL_PARAM_START,        /**< 启动时的准入半窗口（ADC 码），比 RANGE 严 */
    CONTROL_PARAM_OFFSET,       /**< 静摩擦补偿（PWM 码，按输出方向叠加）*/
    CONTROL_PARAM_COUNT         /**< 参数个数（不是参数本身）*/
} control_param_t;

/**
 * 控制器的参数集合。
 *
 * ⚠️ **只读**。在线修改请用 `control_param_set()`，不要直接写这个结构体：
 *    那样绕过了取值范围检查，一个非法的 CENTER 会让倒下保护直接失效。
 *    需要看内容用 `control_params()` 拿指针。
 */
typedef struct {
    float    a_kp, a_ki, a_kd;  /**< 角度环（内环）增益 */
    float    p_kp, p_ki, p_kd;  /**< 位置环（外环）增益 */
    float    pwm_offset;        /**< 静摩擦补偿量 */
    uint16_t center_angle;      /**< 中心角度，ADC 码 */
    uint16_t center_range;      /**< 运行中的倒下判定半窗口，ADC 码 */
    uint16_t start_range;       /**< 启动准入半窗口，ADC 码 */
} control_params_t;

/**
 * 控制器的实时状态快照，供显示与串口查询。
 *
 * 一次 `control_get_status()` 把所有字段取齐，避免调用者分散调用多个
 * getter 时读到**不同时刻**的值（比如角度是新的、位置是旧的）。
 */
typedef struct {
    uint16_t angle;         /**< 摆杆角度原始值，0~4095 */
    int32_t  position;      /**< 横杆累计位置，边沿 */
    int16_t  speed;         /**< 横杆速度，边沿/毫秒 */
    float    angle_target;  /**< 角度环当前目标（外环输出叠加后的）*/
    float    angle_out;     /**< 角度环输出（限幅后，未叠 offset）*/
    float    pos_out;       /**< 位置环输出（限幅后）*/
    int16_t  pwm;           /**< 实际写到电机上的占空比（叠了 offset）*/
    control_state_t state;  /**< 当前状态 */
} control_status_t;

/**
 * @brief 初始化控制器：装载默认参数、清状态、把快照对齐到当前读数。
 *
 * @return error_t ERR_OK 成功；ERR_NOT_INITIALIZED 底层驱动没就绪
 *
 * @note 必须在 bsp_motor / bsp_encoder / bsp_angle 都初始化**之后**调用。
 *       本函数**不启动**控制，初始状态是 STOP。
 *
 * @note 本函数会读一次角度和编码器，让 OLED 第一次画出来就是真值。
 */
error_t control_init(void);

/**
 * @brief 1 ms 节拍任务。**挂在 bsp_tick 上，运行在中断上下文里。**
 *
 * 每个节拍做四件事：
 *   ① 取上一次角度转换的结果，并启动下一次（先取后启，见 .c 里的说明）
 *   ② 推进编码器游标，刷新位置/速度
 *   ③ 倒下保护：RUN 且角度跳出窗口 → 立即停止
 *   ④ 分频出 5 ms 的角度环和 50 ms 的位置环
 *
 * @note 中断上下文：全部是寄存器级操作和几次浮点乘加，无阻塞、无打印。
 */
void control_tick(void);

/**
 * @brief 启动控制。
 *
 * @return error_t ERR_OK 已启动；ERR_NOT_READY 当前角度不在
 *                 `CENTER ± START` 内（也就是摆杆没扶到竖直附近）；
 *                 ERR_NOT_INITIALIZED
 *
 * @note 检查用的是 **`START`（±150，≈±12°）**，不是运行中那个
 *       `RANGE`（±500）。这一条正是用来挡住「摆杆垂着/躺着被误启动」的：
 *       本台实测下垂读数是 1883，落在 `CENTER ± 500` 里，但落在
 *       `CENTER ± 150` 外。详见文件头那两个窗口的说明。
 *
 * @note **会清空两个环的积分和历史误差**，所以每次启动都是干净的，
 *       不会带着上一次运行残留的积分冲出去。
 *
 * @note 仍然建议**用手扶住摆杆**再按 RUN：`START` 挡的是「明确垂着」
 *       这种情形，手扶能顺便消掉手测中心值的残余误差。
 */
error_t control_start(void);

/**
 * @brief 停止控制，并让电机滑行（不是刹车）。
 *
 * @return error_t ERR_OK
 *
 * @note 倒下保护内部也是调它，所以「摔倒了会自己停」和「手动停」
 *       走的是同一条路径，行为一致。
 *
 * @note 停机**不清积分**：那是 control_start() 的事。停机后积分留着，
 *       下次启动时会被 pid_reset() 清掉，所以不影响。
 */
error_t control_stop(void);

/**
 * @brief 当前是否在运行。
 */
bool control_is_running(void);

/**
 * @brief 把横杆位置清零，并把位置目标也归零。
 *
 * @return error_t ERR_OK 成功；ERR_NOT_INITIALIZED 未初始化
 *
 * @note 位置目标和位置**一起**清零是有意的：「把横杆的方位重置」
 *       是一个动作，分两步做容易只做一半（清了位置忘了目标，
 *       横杆会突然朝原来的目标跑）。官方工程里 K4 也是这么做的。
 */
error_t control_zero_position(void);

/**
 * @brief 取/设位置目标（边沿为单位，408 边沿 = 横杆转一圈）。
 *
 * @note 单独给一对 int32 接口而不是塞进 control_param_t，是因为
 *       参数表用的是 float，而 float 只能精确表示 ±2^24 以内的整数 ——
 *       位置虽然远到不了那个量级，但把「整数语义的量」放进浮点参数表
 *       迟早会有人在上面写 0.5。
 */
int32_t control_position_target(void);
error_t control_set_position_target(int32_t target);

/**
 * @brief 把当前状态一次性拷出来。
 *
 * @param out 输出，不可为 NULL
 *
 * @note 拷的过程中控制中断可能刚好跑了一拍，所以这个快照里的各字段
 *       未必来自**同一个** 1 ms。对各字段之间的一致性有要求的场合
 *       （本工程没有），调用前自行关中断。
 */
void control_get_status(control_status_t *out);

/**
 * @brief 读参数表（只读）。
 *
 * @return const control_params_t* 永不为 NULL
 */
const control_params_t *control_params(void);

/**
 * @brief 按枚举读写单个参数。**这是在线改参数的唯一正确入口。**
 *
 * @param p     参数编号；越界返回 ERR_INVALID_PARAM
 * @param value 新值
 *
 * @return error_t ERR_OK 成功；ERR_INVALID_PARAM 编号越界或取值非法
 *
 * @note CENTER / RANGE 会做范围检查（CENTER 必须 ≤ 4095，RANGE 必须 > 0
 *       且不至于让窗口越过 0/4095）。**RANGE = 0 会退化成「角度永远
 *       不在窗口内」，导致 RUN 后立刻停机** —— 这是最容易误设的值，
 *       所以显式拒绝。
 *
 * @note 并发：本函数在主循环（串口命令）里跑，而 control_tick() 在
 *       1 ms 中断里读同一份参数。这里**不加临界区**，理由见 .c。
 */
error_t control_param_set(control_param_t p, float value);

/**
 * @brief 读单个参数。越界返回 0。
 */
float control_param_get(control_param_t p);

/**
 * @brief 参数的可打印名字（如 "AKP"）。越界返回 "?"。
 *
 * @note 串口层用它拼 HELP 文本，写死字符串会造成两处不同步。
 */
const char *control_param_name(control_param_t p);

#endif /* APP_CONTROL_CONTROL_H */
