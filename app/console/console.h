/**
 * @file    console.h
 * @brief   串口调参控制台：ASCII 行协议，给「调参 agent」用的遥控器。
 *
 * ── 为什么要有这一层 ────────────────────────────────────────────────
 *   本工程的目标是让一个 agent 通过串口把 PID 增益调出来。参考工程
 *   里**没有**任何串口改参数的实现（15-倒立摆 的 main.c 注释原文写着
 *   「当前程序暂未使用串口」；00-PID综合测试程序 的调参是「三只电位器
 *   + OLED 菜单 + FLASH」，全是给人手动拧的）。所以这套协议是
 *   **本工程自己设计的**，下面就是它的规格。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 协议规格 ────────────────────────────────────────────────────────
 *   · 命令与响应都以 `\n` 结尾（`\r` 自动忽略，兼容 Windows 串口工具）
 *   · 命令大小写不敏感；参数名一律大写
 *   · 响应只有两种前缀：`OK ` 和 `ERR `。**机器只认这两个前缀**，
 *     认不出来就是协议实现有 bug，而不是「没响应」。
 *
 *   命令                              响应
 *   ─────────────────────────────────────────────────────────────────
 *   SET <参数名> <数值>               OK <参数名>=<值>
 *   GET <参数名>                      OK <参数名>=<值>
 *   GET ALL                           OK AKP=.. AKI=.. .. TARGET=..
 *   STAT                              OK ANGLE=.. POS=.. SPD=..
 *                                        ATAR=.. AOUT=.. POUT=..
 *                                        PWM=.. RUN=.. ST=.. SWR=..
 *   RUN                               OK RUN=1    角度不在启动窗口内则 ERR
 *   SWING                             OK ST=1|2   不在窗口内就自动启摆
 *   STOP                              OK RUN=0
 *   ZERO                              OK POS=0 TARGET=0
 *   TARGET <整数>                     OK TARGET=408
 *   STREAM <0|1>                      OK STREAM=1
 *   HELP                              OK CMD=.. PARAM=..
 *   （任何无法识别的输入）             ERR <原因>
 *
 *   参数名（共 12 个）：AKP AKI AKD PKP PKI PKD CENTER RANGE START OFFSET
 *                       SWP SWT
 *
 * ── RUN 与 SWING 的区别 ────────────────────────────────────────────
 *   `RUN`   **严格**：角度不在 `CENTER ± START`（默认 ±150 ≈ ±12°）内
 *           就回 `ERR NOT_READY`。语义是「我确认摆杆已经立好了，直接闭环」。
 *   `SWING` **自动**：角度已在窗口内 → 等价于 `RUN`；否则 → 先自动启摆，
 *           电机按 `SWP` 的占空比打脉冲把摆杆荡起来，进窗口后自动转成 RUN。
 *           启摆期间 **`RUN=0` 而 `ST=2`**。
 *
 *   保留两套、而不是让 `RUN` 自动回退，有两个理由：
 *     ① 「角度不对就该拒」这条判断还能被单独测到（它的拒绝路径是已验证的）；
 *     ② "会真的甩电机"这件事必须由调用者**显式**要求，不能是发 RUN 的副作用。
 *
 * ── STAT 里的两个状态字段 ──────────────────────────────────────────
 *   `ST`  总状态：0=停止 / 1=双环 PID 在跑 / 2=正在自动启摆
 *   `SWR` 上一次启摆的结局：0=没启摆过 / 1=成功进双环 / 2=超时停机 /
 *         3=启摆途中被 STOP 打断
 *
 *   `RUN` 只有 0/1（双环在不在跑），**它分不出「停着」和「正在启摆」**——
 *   所以判断当前在干什么要看 `ST`，判断"能不能开始调参"才看 `RUN`。
 * ────────────────────────────────────────────────────────────────────
 *   （A*=角度环/内环，P*=位置环/外环，见 control.h）
 *
 * ── 为什么是 ASCII 明文，而不是二进制帧 ────────────────────────────
 *   使用者是「一个会思考的 agent」，不是固定的上位机程序：
 *   · 明文响应可以**直接读**，agent 看到 `ERR BAD_VALUE 0.2.8` 就知道
 *     自己在哪一步写错了，不用去比对错误码表。
 *   · 出问题时可以用任意串口终端手工敲，不需要配套工具。
 *   · 115200 下一行几十字节，占空比极低，带宽完全不是瓶颈。
 *
 *   代价是解析开销和体积，在这里都可以忽略。
 *
 * ── 错误信息必须说清原因 ────────────────────────────────────────────
 *   `ERR` 后面**要带具体原因和出错的那个词**，不能只回一个错误码。
 *   agent 靠这行字自我纠正：看到 `ERR UNKNOWN_PARAM AKQ` 就知道是
 *   拼错了参数名，而看到 `ERR BAD_VALUE 4.5.0` 就知道是数字格式问题。
 *   只回 `ERR 1` 会让 agent 陷入「反复重试同一个错误命令」的死循环。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── ⚠️ 主循环里的时延会影响命令吞吐 ────────────────────────────────
 *   本模块由 `console_poll()` 在主循环里驱动，而主循环里最重的事是
 *   OLED 整屏刷新 —— **实测一屏约 122 ms**（软件 I2C 重发 1 KB 显存）。
 *   这 122 ms 里 console_poll() 完全拿不到 CPU。
 *
 *   115200 下 122 ms 能进来约 1400 字节，而接收环形缓冲只有
 *   `BSP_SERIAL_RX_BUF_SIZE`（256）字节 —— **连发多条命令必定丢**，
 *   而且丢得不声不响。
 *
 *   所以约定：**发一条、等一条响应，再发下一条**。
 *   真丢了可以用 `bsp_serial_rx_dropped()` 确认（STAT 里不带这个计数，
 *   需要时用调试器读）。
 *
 *   刷屏周期由 main.c 的 DISPLAY_PERIOD_MS 控制（当前 500 ms），
 *   所以最坏等待是「恰好撞上一次刷屏的 122 ms」，不是每一轮都等。
 * ────────────────────────────────────────────────────────────────────
 */

#ifndef APP_CONSOLE_CONSOLE_H
#define APP_CONSOLE_CONSOLE_H

#include <stdbool.h>

#include "error.h"

/**
 * @brief 初始化控制台（清空行缓冲、准备接收）。
 *
 * @return error_t ERR_OK
 *
 * @note 必须在 `bsp_serial_init()` 之后调用。本模块不碰 USART 寄存器，
 *       只是协议层。
 */
error_t console_init(void);

/**
 * @brief 主循环任务：收字节、拆行、执行命令、发响应、必要时上报数据流。
 *
 * @note 非阻塞。有多少数据就处理多少，绝不等待。
 *
 * @note **只在主循环里调用**：里面会调 `control_start()` 等控制接口，
 *       也可能拼很长的响应字符串，不适合中断上下文。
 */
void console_poll(void);

/**
 * @brief 数据流（STREAM）是否开着。
 *
 * @note 给主循环用：STREAM 开着的时候上位机在画曲线，屏幕没人在看，
 *       而刷一屏要 ~122 ms 的 CPU（见 console.h 开头的说明）。
 *       主循环据此**暂停刷屏**，把这 122 ms 全部让给串口，
 *       STREAM 的采样率就能从 38 行/秒提到满速 50 行/秒、且不再有
 *       122 ms 的空洞。串流一关，屏幕立刻恢复刷新。
 */
bool console_is_streaming(void);

#endif /* APP_CONSOLE_CONSOLE_H */
