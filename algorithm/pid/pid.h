/**
 * @file    pid.h
 * @brief   位置式 PID，纯算法。
 *
 * ── 这一层为什么单独存在 ────────────────────────────────────────────
 *   它**不包含任何硬件相关的头文件**，输入是 float、输出是 float，
 *   只依赖 <stdint.h>/<stdbool.h>。好处有两个：
 *
 *     ① 可以在 PC 上用 gcc 直接编译、跑单元测试，不用接板子。
 *        控制逻辑的错误（比如积分饱和、符号写反）在 PC 上跑一遍
 *        阶跃响应就能看出来，比烧板子试快得多。
 *     ② 换被控对象（换成平衡车、云台）时这一层原封不动。
 *
 *   所以这里**不许**出现 bsp_xxx / HAL_xxx / 任何寄存器。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 位置式 vs 增量式 ────────────────────────────────────────────────
 *   本工程用**位置式**（输出 = 绝对量），不用增量式，理由：
 *   增量式的输出是「上一次输出 + 增量」，本身带积分性质，一旦因为
 *   限幅、丢步、模式切换导致输出值漂移，误差会**永久累积**在输出上，
 *   而且没法用「直接给一个输出值」的方式接管。倒立摆需要
 *   「停下时输出必须真的是 0」，位置式更合适。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 公式与控制周期 ──────────────────────────────────────────────────
 *   本实现用的是**未归一化到时间**的简化形式（与江协科技官方工程一致）：
 *
 *     out = Kp·e + Ki·Σe + Kd·(e − e_prev)
 *
 *   注意这里的 Ki、Kd **不是**「每秒」的量纲，而是「每个控制周期」的量纲：
 *   Σe 是每次调用累加一次，不是按秒累加。所以：
 *
 *     ⚠️ **改动调用周期 = 改动 Ki 和 Kd 的实际效果。**
 *        周期从 5 ms 改成 2.5 ms，Ki 的实际作用会减半、Kd 会翻倍。
 *        本工程把周期写死成常量（见 control.c 的 CONTROL_ANGLE_PERIOD_MS），
 *        要改周期就得重新整定。
 *
 *   真正的教科书形式会除以 Δt；不做这一步是为了和参考工程的增益对上，
 *   而且整定本来就要重来，多一层换算没有收益。知道这件事就行。
 * ────────────────────────────────────────────────────────────────────
 */

#ifndef ALGORITHM_PID_PID_H
#define ALGORITHM_PID_PID_H

#include <stdbool.h>

/**
 * PID 控制器实例。
 *
 * 分成三段看：参数、限幅、状态。参数和限幅是可以在线改的（串口调参
 * 改的就是前两个），状态是算法自己维护的，**调用者不要动**。
 */
typedef struct {
    /* ── 参数 ─────────────────────────────────────────────────────
     * 三个量纲各不相同的「权重」，物理意义见文件头。
     * 允许为 0：Ki=0 就是去掉积分项（调试时的常规操作）。 */
    float kp;               /**< 比例项权重 */
    float ki;               /**< 积分项权重 */
    float kd;               /**< 微分项权重 */

    /* ── 限幅 ─────────────────────────────────────────────────────
     * 输出限幅是必需的：PID 在误差大时会算出天文数字的输出，
     * 而执行器（电机 PWM）只能接受有限范围。 */
    float out_min;          /**< 输出下限 */
    float out_max;          /**< 输出上限 */

    /* ── 积分限幅（抗饱和）─────────────────────────────────────────
     * 只有 out 限幅是不够的：输出被夹住之后误差依然存在，积分项会
     * **继续无上限地累加**（这叫积分饱和）。等误差反向时，那个巨大
     * 的积分值要花很久才能退回来，表现为「该停的时候刹不住、过冲很大」。
     *
     * 所以必须**单独再夹一次积分累加值**。经验取法是
     * integ_max ≈ out_max / ki（这样积分项单独就能顶满输出，再大没意义），
     * 但 Ki 会在线改、这个关系会失效，所以本实现把上下限做成显式参数，
     * 让调用者（或调参的 agent）能直接控制。
     *
     * 取 integ_min == integ_max == 0 即等价于「禁用积分」。 */
    float integ_min;        /**< 积分累加值下限 */
    float integ_max;        /**< 积分累加值上限 */

    /* ── 输入 / 输出 ──────────────────────────────────────────────
     * 调用者写 target/actual，读 out。 */
    float target;           /**< 目标值（调用者写） */
    float actual;           /**< 实际值（调用者写） */
    float out;              /**< 输出值（本模块写） */

    /* ── 运行时状态（调用者不要动）───────────────────────────────── */
    float err0;             /**< 本次误差 */
    float err1;             /**< 上次误差 */
    float integ;            /**< 误差累加值 */
} pid_t;

/**
 * @brief 清空运行时状态（err0 / err1 / integ / out），**保留参数与限幅**。
 *
 * @param p 控制器；为 NULL 时直接返回（容错，不报错）
 *
 * @note 每次「启动控制」时必须调用。不调用的后果：上一轮运行留下的
 *       积分值会立刻作用到这一轮，启动瞬间电机猛冲一下。
 *       （参考工程靠「Ki 归零时自动清积分」部分绕过了这个问题，
 *        但那只是调试便利，不是正确做法。）
 *
 * @note 不清 target/actual，那两个是调用者的输入。
 */
void pid_reset(pid_t *p);

/**
 * @brief 算一步：读 target/actual，更新 out。
 *
 * @param p 控制器，不可为 NULL
 *
 * @note 计算顺序（与参考工程一致，顺序本身会影响结果，别乱调）：
 *       ① 记下上次误差、算本次误差 e = target − actual
 *       ② 累加积分（Ki==0 时改为清零，见下）
 *       ③ 夹积分
 *       ④ out = Kp·e + Ki·integ + Kd·(e − e_prev)
 *       ⑤ 夹输出
 *
 * @note **Ki==0 时把积分清零**，这是从参考工程保留下来的调试便利：
 *       整定时通常先把 Ki 设 0 观察纯 PD 的效果，此时若积分仍照常累加，
 *       会攒出一个很大的值；等回头把 Ki 调成非 0，那个积压的值会
 *       瞬间顶满输出，电机像被踹了一脚，很难判断到底是哪个参数的问题。
 *
 * @note 本函数**不含时间概念**：调用频率决定 Ki/Kd 的实际强度，
 *       见文件头的警告。
 */
void pid_update(pid_t *p);

#endif /* ALGORITHM_PID_PID_H */
