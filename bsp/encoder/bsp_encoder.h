/**
 * @file    bsp_encoder.h
 * @brief   板载编码电机的正交编码器（TIM3 编码器模式，四倍频）。
 *
 * ── 接线 ────────────────────────────────────────────────────────────
 *   PA6 ── E1A (TIM3_CH1)
 *   PA7 ── E1B (TIM3_CH2)
 *
 *   编码电机内部是「磁铁 + 两个霍尔传感器」，电机旋转让两个霍尔输出
 *   正交的方波（A/B 相差 90°）。TIM3 的编码器接口把这对方波直接接到
 *   计数器上，硬件自动根据两路的相位关系加计数或减计数——
 *   CPU 一个字节都不用搬。
 *
 *   参数在 .ioc 里：TI12 四倍频、IC1 上升沿 / IC2 下降沿（决定方向）、
 *   输入滤波 15（抑制电机碳刷噪声）。引脚上拉由生成的
 *   HAL_TIM_Encoder_MspInit() 配置。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 分辨率 ──────────────────────────────────────────────────────────
 *   手册给的指标是「电机轴转一圈，AB 相共输出 408 个边沿」。
 *   四倍频（TI12）把 A/B 的上升沿和下降沿都计入，所以 408 就是
 *   输出轴转一圈读到的计数增量。位置与转速都以「边沿」为单位。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 为什么不清零计数器 ──────────────────────────────────────────────
 *   常见写法是「读 CNT，然后清零」，用返回值当增量。它有丢数的风险：
 *   读与清零之间到来的边沿会被那次清零抹掉，而且这个窗口关不掉
 *   （清零是写寄存器，不是原子的读-改-写）。
 *
 *   本模块改成**只读不清**，自己记住上次的值，用模 2^16 相减求增量：
 *
 *       int16_t 增量 = (int16_t)(uint16_t)(本次CNT - 上次CNT);
 *
 *   先按 16 位无符号环绕相减、再重新解释成有符号，回绕就自动处理了。
 *   于是有两个好处：
 *     ① 读的时刻可以任意，不会丢边沿——采集频率再低，累计位置也精确；
 *     ② 不需要关中断，因为没有「读-改-写」这种非原子操作。
 *
 *   ⚠️ 正确性前提：两次 update 之间的真实增量绝对值必须小于 32768。
 *      408 边沿/圈、电机 620 RPM ≈ 10.3 圈/秒 → 满速也只有约 4200 边沿/秒，
 *      1 ms 采一次是 4 个边沿，离 32768 差三个数量级，不可能越界。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 使用方式 ────────────────────────────────────────────────────────
 *   按固定周期调用 update()，之后用 total() / delta() 取值
 *   （接口形状与 bsp_pot 的 sample()/raw() 一致）：
 *
 *     bsp_encoder_update();                    // 1 ms 节拍里调（纯寄存器读）
 *     int32_t pos = bsp_encoder_total();       // 累计位置（边沿）
 *     int16_t spd = bsp_encoder_delta();       // 上一次的增量，可当速度
 *
 *   update() 只读一个寄存器并做几次加减，**可以放在中断里**。
 */

#ifndef BSP_ENCODER_H
#define BSP_ENCODER_H

#include <stdbool.h>
#include <stdint.h>

#include "error.h"

/**
 * 输出轴转一圈的计数增量（四倍频后）。
 * 手册：25GA370 的编码器「电机轴转一圈，AB 相共输出 408 个边沿」。
 */
#define BSP_ENCODER_EDGES_PER_REV   (408)

/**
 * @brief 初始化：启动 TIM3 的编码器接口，并把游标对齐到当前计数值。
 *
 * @return error_t ERR_OK 成功；ERR_NOT_READY HAL 启动失败
 *
 * @note 必须在 CubeMX 生成的 MX_TIM3_Init() **之后**调用。
 *
 * @note 末尾那句「把游标对齐到当前 CNT」不能省：否则第一次 update()
 *       算出的增量是「0 减去开机时的 CNT」，是个无意义的巨大值。
 */
error_t bsp_encoder_init(void);

/**
 * @brief 采集一次：推进游标、累加位置，并记下这一段增量。
 *
 * @return error_t ERR_OK 成功；ERR_NOT_INITIALIZED 未初始化就调用
 *
 * @note 只读 TIM3 的 CNT，不清零、不关中断，可安全地在 1 ms 中断里调用。
 */
error_t bsp_encoder_update(void);

/**
 * @brief 累计位置（自上次 reset 以来的边沿总数）。
 *
 * @return int32_t 边沿数，正负表示方向。未初始化时返回 0。
 */
int32_t bsp_encoder_total(void);

/**
 * @brief 上一次 update() 得到的增量（边沿）。
 *
 * @return int16_t 正负表示方向。未初始化时返回 0。
 *
 * @note 除以 update 的调用周期就是转速（边沿/秒）。调用者需要自己
 *       保证周期恒定，本模块不知道时间。
 */
int16_t bsp_encoder_delta(void);

/**
 * @brief 把累计位置清零（游标对齐到当前计数值，避免把清零前的
 *        残余增量算进下一段）。
 */
error_t bsp_encoder_reset(void);

/**
 * @brief 软件反转计数方向。
 *
 * @param invert true 表示把增量取反
 *
 * @note 正常接线时**不需要**用它：方向由 CubeMX 里 IC1/IC2 的极性配置
 *       决定，已与电机正转方向对齐。它是万一 A/B 相接反（或换电机）
 *       时的软件兜底，省得改 .ioc 重新生成。
 */
error_t bsp_encoder_set_invert(bool invert);

#endif /* BSP_ENCODER_H */
