/**
 * @file    bsp_motor.h
 * @brief   板载直流电机：TB6612FNG 的 A 路驱动 + 25GA370 编码电机。
 *
 * ── 接线 ────────────────────────────────────────────────────────────
 *   PA0   ── PWMA (TIM2_CH1)   转速：PWM 占空比
 *   PB12  ── AIN1              转向（与 PB13 配合）
 *   PB13  ── AIN2              转向（与 PB12 配合）
 *   STBY  ── 板上直接接 3V3     常使能，代码不用管
 *
 *   PA0 的复用推挽配置由 CubeMX 生成的 HAL_TIM_MspPostInit() 完成，
 *   PB12/PB13 的推挽输出由 MX_GPIO_Init() 完成。本模块只调用生成的宏
 *   （MOTOR_AIN1_Pin / MOTOR_AIN1_GPIO_Port），不自己写引脚定义——
 *   理由与按键相同，见 bsp/key/bsp_key.c 的说明。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 为什么是 20 kHz ──────────────────────────────────────────────────
 *   TIM2 挂在 APB1 上。APB1 预分频 = 2，而 STM32 的规则是「APB 预分频
 *   大于 1 时定时器时钟 = 2 × PCLKx」，所以 TIM2 的时钟是 72 MHz：
 *
 *       72 000 000 ÷ (PSC+1) ÷ (ARR+1) = 72e6 ÷ 2 ÷ 1800 = 20 kHz
 *
 *   20 kHz 高于人耳上限，电机不会发出啸叫（PWM 频率落在音频段会听到
 *   持续的「嗞」声）。这两个值配在 .ioc 里，**改定时器参数必须同步改
 *   本文件的 BSP_MOTOR_PWM_ARR**，否则占空比换算会静默算错。
 *
 *   ⚠️ ARR 取 1799 而**不是** 99，是为了**分辨率**（1/1800 而不是 1/100）。
 *      两种取法都是 20 kHz，但控制环需要细步长。理由见 BSP_MOTOR_PWM_ARR。
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 两个「停」不是一回事 ────────────────────────────────────────────
 *   TB6612 的真值表里，两个方向脚决定四种状态：
 *
 *     AIN1  AIN2   结果
 *      0     0     Stop（输出高阻，电机惯性滑行）
 *      1     1     Short brake（电机绕组被短接，快速刹停）
 *      0     1     一个方向转
 *      1     0     另一个方向转
 *
 *   `bsp_motor_set_duty(0)` 走的是「滑行」，与 `bsp_motor_coast()` 等价。
 *   要快速停住用 `bsp_motor_brake()`。**两者都必须在初始化之后调用。**
 * ────────────────────────────────────────────────────────────────────
 */

#ifndef BSP_MOTOR_H
#define BSP_MOTOR_H

#include <stdint.h>

#include "error.h"

/**
 * duty 的绝对值上限，同时也是 100% 占空比对应的值。
 *
 * **duty 就是 CCR 的原始值**：占空比 = CCR / (ARR+1) = |duty| / 1800，
 * 不需要任何换算系数（这是 ARR 特意取 1799 的原因，见文件头）。
 *
 * ⚠️ 这个数**不是百分数**：1800 对应 100% 占空比，不是 100。
 *    它取 1800 而不是 99，是为了要**分辨率**——见下面 BSP_MOTOR_PWM_ARR 的说明。
 */
#define BSP_MOTOR_DUTY_MAX      (1800)

/**
 * 与 .ioc 里 TIM2 的 ARR 绑死（和 BSP_TICK_PERIOD_MS 与 TIM1 的关系一样）。
 * 改 .ioc 时必须同步改这里，否则占空比会静默算错一个倍数。
 *
 * ── 为什么是 1799 而不是 99 ──────────────────────────────────────
 *   两个取值都能配出 20 kHz，但**占空比分辨率差 18 倍**：
 *
 *     ARR=99   （PSC=35）→ 分辨率 1/100  = 1%      步长太粗
 *     ARR=1799 （PSC=1） → 分辨率 1/1800 = 0.056%
 *
 *   控制环在平衡点附近只输出很小的量，1% 的步长会让电机在正反 1% 之间
 *   来回跳（量化抖动），而 0.056% 的步长足够细腻。
 *
 * ⚠️ **代价：参考工程的 PID 增益不能直接照抄，要乘以 18。**
 *
 *   江协科技那三个参考工程（15-倒立摆、00-PID综合测试程序 V1.0/V1.1 的
 *   Mode3）的 PWM 时基都是 ARR=99（`PWM.c` 里 `TIM_Period = 100 - 1`），
 *   即**满量程对应 100 个计数**；本工程是 1800，正好差 18 倍。
 *
 *   真正决定物理强度的是**占空比**，不是裸计数：
 *
 *       参考：duty = Kp_ref × e / 100
 *       本机：duty = Kp_ours × e / 1800
 *       两者 duty 相同  ⟹  Kp_ours = Kp_ref × 18
 *
 *   照抄参考里的 0.25 会得到一个**弱 18 倍**的控制器，摆杆立不住，
 *   而且很容易误判成「参考参数是错的」。本工程 control.c 里的默认增益
 *   已经按 ×18 换算过了。
 *
 *   （注意：外环位置环的输出限幅 ±100 是**角度码**，与 PWM 量程无关，
 *     不参与这个换算。）
 * ────────────────────────────────────────────────────────────────
 */
#define BSP_MOTOR_PWM_ARR       (BSP_MOTOR_DUTY_MAX - 1)

/**
 * @brief 初始化电机：方向脚置 0、占空比置 0，然后启动 PWM。
 *
 * @return error_t ERR_OK 成功；ERR_NOT_READY PWM 启动失败
 *
 * @note 必须在 CubeMX 生成的 MX_TIM2_Init() 与 MX_GPIO_Init() **之后**调用。
 *
 * @note **本函数保证上电时电机不动**：先写方向脚和 CCR，最后才
 *       HAL_TIM_PWM_Start()。倒立摆上电乱摆很危险，这个顺序不能调换。
 *
 * @note HAL_TIM_PWM_Start() 只调一次。重复调用会因为通道状态已是 BUSY
 *       而返回错误——它不只是重写寄存器。
 */
error_t bsp_motor_init(void);

/**
 * @brief 设置转速与方向。
 *
 * @param duty -BSP_MOTOR_DUTY_MAX ~ +BSP_MOTOR_DUTY_MAX（当前为 ±1800，
 *             即 CCR 原始值，满量程对应 100% 占空比）。正数是一个方向，
 *             负数是另一个方向，0 表示滑行停转。
 *             **超出范围会被夹紧到 ±BSP_MOTOR_DUTY_MAX。**
 *
 * @return error_t ERR_OK 成功；ERR_NOT_INITIALIZED 未初始化就调用
 *
 * @note **越界为什么是夹紧而不是报错**：本接口的主要调用者是 PID 控制环，
 *       它的输出偶尔越界属于正常现象（限幅前的瞬态）。此时让电机停摆
 *       比夹紧到边界危险得多，所以安全性交给夹紧，不返回错误。
 *       需要严格边界检查的场合，调用前自行判断。
 *
 * @note 方向脚与 CCR 是分两步写的，中间会有极短的不一致窗口（例如
 *       方向已翻转但占空比还是旧值）。这在 20 kHz 下是几微秒量级，
 *       对电机没有任何影响；反过来先写 CCR 也一样。真正会出问题的是
 *       「先启动 PWM 再写方向」，所以初始化顺序才是那样定的。
 */
error_t bsp_motor_set_duty(int16_t duty);

/**
 * @brief 滑行停转：两个方向脚都置 0（输出高阻），占空比置 0。
 *
 * 用于正常停机、紧急停机。电机靠惯性自己停下。
 */
error_t bsp_motor_coast(void);

/**
 * @brief 刹车：两个方向脚都置 1（绕组短接），占空比置 0。
 *
 * @note 比 coast 停得快，但电流大。**不要长时间保持这个状态**，
 *       也不要用它做常规停机——真实场合是「停止」而不是「急停」。
 */
error_t bsp_motor_brake(void);

/**
 * @brief 取回当前设定的 duty（夹紧之后的值）。
 *
 * @return int16_t ±BSP_MOTOR_DUTY_MAX；未初始化时返回 0
 *
 * @note 读的是本模块记录的值，不是回读寄存器。用于显示与调试。
 */
int16_t bsp_motor_duty(void);

#endif /* BSP_MOTOR_H */
